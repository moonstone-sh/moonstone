//! The `moonstone` Lua modules written into every project environment.
//!
//!     require("moonstone.target")    flavor the environment was linked for
//!     require("moonstone.project")   the project's own manifest metadata
//!     require("moonstone.variants")  flavor-variant selection and searcher
//!     require("moonstone")           all three
//!
//! `target` and `project` are plain constant tables, generated at link time.
//! Without a bundler they are ordinary modules; Quaver may treat every field
//! as a compile-time constant and drop the branches that test it, because a
//! project's environment is relinked whenever the runtime or manifest
//! changes. Nothing machine-specific (absolute paths, timestamps) goes into
//! them, so the same project yields the same bytes on every host with the
//! same flavor.

const std = @import("std");
const flavor_mod = @import("../platform/flavor.zig");
const error_context = @import("../diagnostics/error_context.zig");

pub const variants_lua = @embedFile("../assets/lua/moonstone/variants.lua");

pub const Runtime = struct {
    name: []const u8,
    version: []const u8,
    abi: []const u8,
};

pub const Project = struct {
    name: []const u8,
    version: []const u8,
    kind: []const u8,
    description: ?[]const u8 = null,
};

pub const Dependency = struct {
    name: []const u8,
    version: []const u8,
    role: []const u8,
};

const init_lua =
    \\-- Generated by `moon sync`. Do not edit.
    \\return {
    \\  target = require("moonstone.target"),
    \\  project = require("moonstone.project"),
    \\  variants = require("moonstone.variants"),
    \\}
    \\
;

/// Write the modules under `share_dir/moonstone/`. A dependency that already
/// projected a `moonstone` module would be shadowed silently, so that is a
/// conflict instead.
pub fn write(
    allocator: std.mem.Allocator,
    io: std.Io,
    share_dir: std.Io.Dir,
    flavor: flavor_mod.Flavor,
    runtime: Runtime,
    project: Project,
    dependencies: []const Dependency,
) !void {
    for ([_][]const u8{ "moonstone", "moonstone.lua" }) |reserved| {
        if (share_dir.access(io, reserved, .{})) |_| {
            error_context.setFmt(
                allocator,
                "A dependency projects a Lua module named '{s}', which Moonstone reserves for the generated 'moonstone' modules. Rename that module or drop the dependency, then run 'moon sync'.",
                .{reserved},
            );
            return error.ModuleConflict;
        } else |err| if (err != error.FileNotFound) return err;
    }

    try share_dir.createDirPath(io, "moonstone");
    var dir = try share_dir.openDir(io, "moonstone", .{});
    defer dir.close(io);

    try writeFile(io, dir, "init.lua", init_lua);
    try writeFile(io, dir, "variants.lua", variants_lua);

    const target_source = try renderTarget(allocator, flavor, runtime);
    defer allocator.free(target_source);
    try writeFile(io, dir, "target.lua", target_source);

    const project_source = try renderProject(allocator, project, dependencies);
    defer allocator.free(project_source);
    try writeFile(io, dir, "project.lua", project_source);
}

fn writeFile(io: std.Io, dir: std.Io.Dir, name: []const u8, content: []const u8) !void {
    const file = try dir.createFile(io, name, .{});
    defer file.close(io);
    try file.writeStreamingAll(io, content);
}

pub fn renderTarget(allocator: std.mem.Allocator, flavor: flavor_mod.Flavor, runtime: Runtime) ![]const u8 {
    var aw = std.Io.Writer.Allocating.init(allocator);
    defer aw.deinit();
    const w = &aw.writer;

    const id = try flavor.id(allocator);
    defer allocator.free(id);

    try w.writeAll(
        \\-- Generated by `moon sync`. Do not edit.
        \\---@class moonstone.Target
        \\---@field id string           `lua54-aarch64-macos`; also exported as MOONSTONE_TARGET
        \\---@field family "lua"|"luajit"|"luau"
        \\---@field level integer       language level: 51 ... 55 (LuaJIT and Luau report 51)
        \\---@field os "linux"|"macos"|"windows"|"freebsd"
        \\---@field arch "x86_64"|"aarch64"|"riscv64"
        \\---@field runtime {name: string, version: string, abi: string}
        \\---@type moonstone.Target
        \\return {
        \\
    );
    try w.writeAll("  id = ");
    try writeLuaString(w, id);
    try w.writeAll(",\n  family = ");
    try writeLuaString(w, flavor.family.asString());
    try w.print(",\n  level = {d},\n  os = ", .{flavor.level});
    try writeLuaString(w, flavor.os);
    try w.writeAll(",\n  arch = ");
    try writeLuaString(w, flavor.arch);
    try w.writeAll(",\n  runtime = { name = ");
    try writeLuaString(w, runtime.name);
    try w.writeAll(", version = ");
    try writeLuaString(w, runtime.version);
    try w.writeAll(", abi = ");
    try writeLuaString(w, runtime.abi);
    try w.writeAll(" },\n}\n");
    return aw.toOwnedSlice();
}

pub fn renderProject(allocator: std.mem.Allocator, project: Project, dependencies: []const Dependency) ![]const u8 {
    var aw = std.Io.Writer.Allocating.init(allocator);
    defer aw.deinit();
    const w = &aw.writer;

    try w.writeAll(
        \\-- Generated by `moon sync`. Do not edit.
        \\---@class moonstone.Project
        \\---@field name string
        \\---@field version string
        \\---@field kind "script"|"lib"|"bin"|"runtime"|"libtool"
        \\---@field description string?
        \\---@field dependencies {name: string, version: string, role: string}[] sorted by name
        \\---@type moonstone.Project
        \\return {
        \\
    );
    try w.writeAll("  name = ");
    try writeLuaString(w, project.name);
    try w.writeAll(",\n  version = ");
    try writeLuaString(w, project.version);
    try w.writeAll(",\n  kind = ");
    try writeLuaString(w, project.kind);
    if (project.description) |description| {
        try w.writeAll(",\n  description = ");
        try writeLuaString(w, description);
    }

    const sorted = try allocator.dupe(Dependency, dependencies);
    defer allocator.free(sorted);
    std.mem.sort(Dependency, sorted, {}, struct {
        fn lessThan(_: void, a: Dependency, b: Dependency) bool {
            return std.mem.order(u8, a.name, b.name) == .lt;
        }
    }.lessThan);

    try w.writeAll(",\n  dependencies = {\n");
    for (sorted) |dependency| {
        try w.writeAll("    { name = ");
        try writeLuaString(w, dependency.name);
        try w.writeAll(", version = ");
        try writeLuaString(w, dependency.version);
        try w.writeAll(", role = ");
        try writeLuaString(w, dependency.role);
        try w.writeAll(" },\n");
    }
    try w.writeAll("  },\n}\n");
    return aw.toOwnedSlice();
}

/// A double-quoted Lua string literal that every Lua 5.1+ lexer reads back
/// byte for byte (decimal escapes only; `\x` is 5.2+).
fn writeLuaString(w: *std.Io.Writer, value: []const u8) !void {
    try w.writeByte('"');
    for (value) |ch| switch (ch) {
        '\\' => try w.writeAll("\\\\"),
        '"' => try w.writeAll("\\\""),
        '\n' => try w.writeAll("\\n"),
        0...9, 11...31, 127 => try w.print("\\{d:0>3}", .{ch}),
        else => try w.writeByte(ch),
    };
    try w.writeByte('"');
}

test "target module is a constant table" {
    const allocator = std.testing.allocator;
    const source = try renderTarget(allocator, .{ .family = .lua, .level = 54, .os = "macos", .arch = "aarch64" }, .{ .name = "lua", .version = "5.4.7", .abi = "lua54" });
    defer allocator.free(source);
    try std.testing.expect(std.mem.indexOf(u8, source, "  id = \"lua54-aarch64-macos\",\n") != null);
    try std.testing.expect(std.mem.indexOf(u8, source, "  level = 54,\n") != null);
    try std.testing.expect(std.mem.indexOf(u8, source, "runtime = { name = \"lua\", version = \"5.4.7\", abi = \"lua54\" }") != null);
}

test "project module sorts dependencies and escapes strings" {
    const allocator = std.testing.allocator;
    const source = try renderProject(allocator, .{ .name = "app", .version = "1.0.0", .kind = "lib", .description = "say \"hi\"\n\x01" }, &.{
        .{ .name = "zeta", .version = "2.0.0", .role = "runtime" },
        .{ .name = "alpha", .version = "1.0.0", .role = "dev" },
    });
    defer allocator.free(source);
    try std.testing.expect(std.mem.indexOf(u8, source, "description = \"say \\\"hi\\\"\\n\\001\"") != null);
    const alpha = std.mem.indexOf(u8, source, "\"alpha\"").?;
    const zeta = std.mem.indexOf(u8, source, "\"zeta\"").?;
    try std.testing.expect(alpha < zeta);
}
